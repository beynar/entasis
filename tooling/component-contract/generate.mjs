function skillInventory(entries) {
	const categories = new Map();
	const modules = [];

	for (const entry of entries.filter((candidate) => candidate.visibility === 'public')) {
		if (entry.docs.length === 0) {
			modules.push(entry);
			continue;
		}
		for (const doc of entry.docs) {
			const category = categories.get(doc.category) ?? [];
			category.push({ entry, doc });
			categories.set(doc.category, category);
		}
	}

	const categorySections = [...categories]
		.map(
			([category, records]) =>
				`### ${category}\n\n${records
					.map(
						({ entry, doc }) =>
							`- \`${entry.subpath === './package.json' ? 'svelai/package.json' : `svelai/${entry.subpath.slice(2)}`}\` — ${doc.label} (${doc.route})`
					)
					.join('\n')}`
		)
		.join('\n\n');
	const moduleSection = modules
		.map(
			(entry) =>
				`- \`${entry.subpath === './package.json' ? 'svelai/package.json' : `svelai/${entry.subpath.slice(2)}`}\` — ${entry.capabilities.join(', ')}`
		)
		.join('\n');

	// Blank lines around the marker comments keep the block Prettier-stable.
	return `<!-- component-contract:inventory:start -->

## Generated Package Inventory

This section is generated from \`tooling/component-contract/manifest.ts\`.

${categorySections}

### Utilities and entrypoints

${moduleSection}

<!-- component-contract:inventory:end -->`;
}

function updateSkillInventory(source, inventory) {
	const start = '<!-- component-contract:inventory:start -->';
	const end = '<!-- component-contract:inventory:end -->';
	const startIndex = source.indexOf(start);
	const endIndex = source.indexOf(end);

	if (startIndex === -1 && endIndex === -1) return `${source.trimEnd()}\n\n${inventory}\n`;
	if (startIndex === -1 || endIndex === -1 || endIndex < startIndex) {
		throw new Error('Malformed component contract inventory markers in svelai skill');
	}
	return `${source.slice(0, startIndex)}${inventory}${source.slice(endIndex + end.length)}`;
}

async function emit(relativePath, output) {
	if (!relativePath.endsWith('.md')) {
		const filepath = path.join(root, relativePath);
		output = await prettier.format(output, {
			...(await prettier.resolveConfig(filepath)),
			filepath
		});
	}
	let current = null;
	try {
		current = await read(relativePath);
	} catch (error) {
		if (error.code !== 'ENOENT') throw error;
	}

	if (current === output) return;
	changedFiles.push(relativePath);
	if (!isCheck) {
		await fs.mkdir(path.dirname(path.join(root, relativePath)), { recursive: true });
		await fs.writeFile(path.join(root, relativePath), output);
	}
}

const entries = await loadManifest();
await assertManifest(entries);
if (errors.length > 0) {
	console.error(errors.join('\n'));
	process.exit(1);
}

const packageJson = JSON.parse(await read('package.json'));
await emit('package.json', packageJsonOutput(entries, packageJson));
await emit('src/lib/generated/componentMcpRegistry.ts', mcpRegistryOutput(entries));
await emit('src/routes/componentNavigation.generated.ts', navigationOutput(entries));
await emit('src/lib/generated/componentContract.ts', metadataOutput(entries));
await emit(
	'src/lib/generated/componentAliases.js',
	`${generatedBanner}export const componentAliases = ${JSON.stringify(
		Object.fromEntries(
			entries
				.filter((entry) => entry.subpath && entry.sourceIndex !== 'package.json')
				// Vite uses the first matching prefix, so nested exports must come first.
				.sort((left, right) => right.subpath.split('/').length - left.subpath.split('/').length)
				.map((entry) => [
					`svelai/${entry.subpath.slice(2)}`,
					`./${entry.sourceIndex.replace(/\*\.ts$/, '*')}`
				])
		),
		null,
		'\t'
	)};\n`
);
await emit('src/routes/components/+page.svelte', inventoryPageOutput());

// `.claude/skills/svelai` is the canonical skill tree; `.agents/skills/svelai` is a
// generated mirror so both agent runtimes read identical docs.
const inventory = skillInventory(entries);
const canonicalSkillDir = '.claude/skills/svelai';
const mirrorSkillDir = '.agents/skills/svelai';
await emit(
	`${canonicalSkillDir}/SKILL.md`,
	updateSkillInventory(await read(`${canonicalSkillDir}/SKILL.md`), inventory)
);
for (const file of await fs.readdir(path.join(root, canonicalSkillDir))) {
	if (!file.endsWith('.md')) continue;
	await emit(`${mirrorSkillDir}/${file}`, await read(`${canonicalSkillDir}/${file}`));
}

if (isCheck && changedFiles.length > 0) {
	console.error(
		`Component contract drift detected:\n${changedFiles.map((file) => `- ${file}`).join('\n')}`
	);
	process.exit(1);
}

if (!isCheck && changedFiles.length > 0) {
	console.log(
		`Generated component contract:\n${changedFiles.map((file) => `- ${file}`).join('\n')}`
	);
}
